"""Generate and gate the observed documentation layer for this repository.

Implements the L2 layer of the documentation charter: everything this module
emits is derived from the working tree (Tach policy, Python AST, tickets)
and never hand-edited. ``check`` makes staleness and broken documentation
pointers hard failures, so the generated catalog cannot drift and hand
documents cannot reference files that vanished. ``stats`` reports advisory
numbers that make documentation restatement and code narration visible
without gating on taste.
"""
import argparse
import ast
import json
import re
import sys
import tomllib
from pathlib import Path

STAMP = re.compile(r"^<!-- rendered from revision ([0-9a-f]{40}) -->$", re.MULTILINE)
PATH_TOKEN = re.compile(r"`([\w./-]+\.(?:py|gd|md|toml|json|scm|mjs))`")
REFERENTIAL = re.compile(r"REQ|§|res://|user://|L\d+|[A-Z]+-\d|http")
HAND_DOCS = ("AGENTS.md", "README.md", "docs/documentation-charter.md",
             "OPENCODE_HARNESS_HANDOFF.md")
CATALOG = Path("docs/usage/catalog.md")


def _public_names(source):
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []
    return sorted({node.name for node in tree.body
                   if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
                   and not node.name.startswith("_")})


def build(root):
    """Collect the observed layer: modules, public names, tickets, coverage."""
    root = Path(root)
    policy = tomllib.loads((root / "tach.toml").read_text(encoding="utf-8"))
    modules = {}
    for module in policy["modules"]:
        path = module["path"].replace(".", "/") + ".py"
        source = (root / path).read_text(encoding="utf-8") if (root / path).is_file() else ""
        lines = source.splitlines()
        modules[module["path"]] = {
            "file": path, "depends_on": module["depends_on"],
            "public": _public_names(source),
            "code_lines": sum(1 for line in lines if line.strip()),
            "comment_lines": sum(1 for line in lines
                                 if line.strip().startswith("#") and not line.startswith("#!")),
        }
    tickets_dir = root / "tickets"
    tickets = []
    for ticket_path in sorted(tickets_dir.glob("*.json")):
        ticket = json.loads(ticket_path.read_text(encoding="utf-8"))
        acceptance = "tests/test_" + ticket["id"].lower().replace("-", "_") + ".py"
        tickets.append({"id": ticket["id"], "components": ticket["components"],
                         "open": not (root / acceptance).is_file(),
                         "acceptance": acceptance,
                         "requirements": len(ticket["requirements"])})
    return {"modules": modules, "tickets": tickets}


def render(data, revision):
    """Markdown for the observed layer; deterministic, never hand-edited."""
    lines = ["<!-- DO NOT EDIT: generated by scripts/doc_catalog.py (render) -->",
             f"<!-- rendered from revision {revision} -->",
             "", "# Component catalog (generated)", "",
             "Every fact on this page is derived from the tree: Tach policy for",
             "boundaries, the AST for public names, `tickets/` for intent. Zoom:",
             "component -> file -> symbol -> revision. Regenerate with",
             "`python scripts/doc_catalog.py render`; gate with `check`.", "",
             "| Component | File | Public names | Depends on | Open tickets | Coverage |",
             "|---|---|---:|---|---|---|"]
    for name, module in data["modules"].items():
        open_ids = [t["id"] for t in data["tickets"]
                    if name in t["components"] and t["open"]]
        coverage = [t["id"] for t in data["tickets"]
                    if name in t["components"] and not t["open"]]
        lines.append(f"| {name} | `{module['file']}` | {len(module['public'])} "
                     f"| {', '.join(module['depends_on']) or '-'} "
                     f"| {', '.join(open_ids) or '-'} "
                     f"| {', '.join(coverage) or '-'} |")
    lines += ["", "## Tickets", "",
              "| Ticket | Components | Requirements | Acceptance | Status |", "|---|---|---:|---|---|"]
    for ticket in data["tickets"]:
        lines.append(f"| {ticket['id']} | {', '.join(ticket['components'])} "
                     f"| {ticket['requirements']} | `{ticket['acceptance']}` "
                     f"| {'open' if ticket['open'] else 'verified'} |")
    lines += ["", "## Public API by component", ""]
    for name, module in data["modules"].items():
        names = ", ".join(f"`{n}`" for n in module["public"]) or "-"
        lines.append(f"- **{name}** (`{module['file']}`): {names}")
    return "\n".join(lines) + "\n"


def check(root):
    """Hard gates: generated catalog freshness and documentation pointers."""
    root = Path(root)
    problems = []
    catalog = root / CATALOG
    if not catalog.is_file():
        problems.append(f"{CATALOG}: generated catalog is missing; run render")
    else:
        committed = STAMP.sub("", catalog.read_text(encoding="utf-8"))
        fresh = STAMP.sub("", render(build(root), "0" * 40))
        if committed.strip() != fresh.strip():
            problems.append(f"{CATALOG}: stale; re-run scripts/doc_catalog.py render")
    documents = [rel for rel in HAND_DOCS if rel != "OPENCODE_HARNESS_HANDOFF.md"]
    documents += [str(p.relative_to(root)).replace("\\", "/")
                  for p in sorted((root / "docs").rglob("*.md"))
                  if p.relative_to(root).as_posix() != CATALOG.as_posix()]
    for rel in documents:
        path = root / rel
        if not path.is_file():
            continue
        for token in sorted(set(PATH_TOKEN.findall(path.read_text(encoding="utf-8")))):
            # Dot-prefixed trees (ignored evidence dirs) and bare filenames are
            # prose mentions; only repository paths are gate-checked pointers.
            if token.startswith(".") or "/" not in token:
                continue
            if not (root / token).exists():
                problems.append(f"{rel}: references missing path `{token}`")
    return problems


def stats(root):
    """Advisory numbers: documentation restatement and code narration."""
    root = Path(root)
    catalog_text = (root / CATALOG).read_text(encoding="utf-8") if (root / CATALOG).is_file() else ""
    catalog_sentences = _sentences(catalog_text)
    drift = []
    for rel in HAND_DOCS:
        path = root / rel
        if not path.is_file():
            continue
        for sentence in _sentences(path.read_text(encoding="utf-8")):
            overlap = max((_jaccard(sentence, other) for other in catalog_sentences),
                          default=0.0)
            if overlap >= 0.6:
                drift.append({"document": rel, "overlap": round(overlap, 2),
                              "sentence": sentence[:120]})
    comments = {}
    policy = tomllib.loads((root / "tach.toml").read_text(encoding="utf-8"))
    for module in policy["modules"]:
        file = root / (module["path"].replace(".", "/") + ".py")
        if not file.is_file():
            continue
        lines = file.read_text(encoding="utf-8").splitlines()
        comment = [line.strip().lstrip("#").strip() for line in lines
                   if line.strip().startswith("#") and not line.startswith("#!")]
        comments[module["path"]] = {
            "comment_lines": len(comment),
            "non_referential": sum(1 for text in comment if not REFERENTIAL.search(text)),
        }
    return {"drift": sorted(drift, key=lambda row: -row["overlap"])[:10], "comments": comments}


def _sentences(text):
    return [chunk.strip() for chunk in re.split(r"[\n.]", text)
            if len(chunk.strip()) > 30]


def _jaccard(a, b):
    left, right = set(a.lower().split()), set(b.lower().split())
    return len(left & right) / len(left | right) if left | right else 0.0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("op", choices=["render", "check", "stats"])
    parser.add_argument("root", nargs="?", default=".")
    args = parser.parse_args(argv)
    root = Path(args.root)
    if args.op == "render":
        revision = _revision(root)
        target = root / CATALOG
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render(build(root), revision), encoding="utf-8")
        print(f"rendered {CATALOG} from {revision[:12]}")
        return 0
    if args.op == "check":
        problems = check(root)
        if problems:
            print("Documentation gates")
            for problem in problems:
                print(f"[FAIL] {problem}")
            return 1
        print("[OK] generated catalog fresh; documentation pointers resolve")
        return 0
    print(json.dumps(stats(root), indent=2))
    return 0


def _revision(root):
    try:
        import subprocess
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, capture_output=True,
                              encoding="utf-8", timeout=30).stdout.strip()
    except Exception:
        return "0" * 40


if __name__ == "__main__":
    sys.exit(main())
